const ASCII_DIGITS = "0123456789";
const URDU_DIGITS = "۰۱۲۳۴۵۶۷۸۹";
const HINDI_DIGITS = "०१२३४५६७८९";

function normalizeDigits(value: string): string {
  return value.replace(/[۰-۹٠-٩०-९]/g, digit => {
    const urduIndex = URDU_DIGITS.indexOf(digit);
    if (urduIndex >= 0) return ASCII_DIGITS[urduIndex];
    const arabicIndex = "٠١٢٣٤٥٦٧٨٩".indexOf(digit);
    if (arabicIndex >= 0) return ASCII_DIGITS[arabicIndex];
    return ASCII_DIGITS[HINDI_DIGITS.indexOf(digit)];
  });
}

function localizeDigits(value: string, language: InterfaceLanguage): string {
  if (language === "en") return normalizeDigits(value);
  const digits = language === "ur" ? URDU_DIGITS : HINDI_DIGITS;
  return normalizeDigits(value).replace(/\d/g, digit => digits[Number(digit)]);
}

export function normalizeInterfaceLanguage(language: string | null | undefined): InterfaceLanguage {
  return language === "ur" || language === "hi" ? language : "en";
}

export function getInterfaceLocale(language: string | null | undefined): string {
  const normalized = normalizeInterfaceLanguage(language);
  return normalized === "ur" ? "ur-PK" : normalized === "hi" ? "hi-IN" : "en-US";
}

